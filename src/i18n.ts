const dictionaries: Record<string, typeof en> = { en, 'zh-CN': zhCN };

export const i18n = dictionaries[siteConfig.language] ?? en;

export function __(key: string, ...args: (string | number)[]): string {
	let value: unknown = i18n;
	for (const part of key.split('.')) {
		value = (value as Record<string, unknown>)?.[part];
	}
	let result = typeof value === 'string' ? value : key;
	args.forEach((arg) => {
		result = result.replace('%s', String(arg));
	});
	return result;
}

/** Date formatting, hexo-like tokens. */
export function formatDate(date: Date, format: string): string {
	const pad = (n: number) => String(n).padStart(2, '0');
	const tokens: Record<string, string> = {
		YYYY: String(date.getFullYear()),
		YY: String(date.getFullYear()).slice(-2),
		MM: pad(date.getMonth() + 1),
		M: String(date.getMonth() + 1),
		DD: pad(date.getDate()),
		D: String(date.getDate()),
		HH: pad(date.getHours()),
		H: String(date.getHours()),
		mm: pad(date.getMinutes()),
		m: String(date.getMinutes()),
		ss: pad(date.getSeconds()),
		s: String(date.getSeconds()),
	};
	return format.replace(/YYYY|YY|MM|M|DD|D|HH|H|mm|m|ss|s/g, (token) => tokens[token]);
}
